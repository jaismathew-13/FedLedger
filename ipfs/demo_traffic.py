"""Demonstrate local IPFS add/retrieve with dummy data, not medical/model data."""
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from architecture_io import LocalIPFS, sha256, write_json
from train_fedprox import record


def main():
    started = datetime.now(timezone.utc).isoformat()
    folder = ROOT/'ipfs'/'demo_outputs'/datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S_%fZ')
    folder.mkdir(parents=True)
    record(f'IPFS dummy traffic demonstration start: {folder}; generated bytes only; no images or model checkpoints.')
    ipfs = LocalIPFS()
    before = ipfs.post('stats/bw').json()
    source = folder/'dummy-traffic.bin'
    with source.open('wb') as stream:
        stream.write(b'DUMMY IPFS STORAGE DEMO - NOT A MODEL OR PATIENT FILE\n')
        for _ in range(64):
            stream.write(os.urandom(64 * 1024))
    print(f'Generated dummy file: {source.stat().st_size:,} bytes', flush=True)
    start = time.perf_counter()
    artifact = ipfs.add(source)
    upload_seconds = time.perf_counter() - start
    print(f'Added and pinned CID: {artifact["cid"]}', flush=True)
    mfs_folder = '/project-demos'
    ipfs.post('files/mkdir', params={'arg': mfs_folder, 'parents': 'true'})
    mfs_path = mfs_folder + '/' + folder.name + '-dummy-traffic.bin'
    ipfs.post('files/cp', params=[('arg', '/ipfs/' + artifact['cid']), ('arg', mfs_path)])
    print(f'Desktop Files location: {mfs_path}', flush=True)
    start = time.perf_counter()
    target = ipfs.fetch(artifact['cid'], artifact['sha256'], folder/'retrieved-dummy.bin')
    retrieval_seconds = time.perf_counter() - start
    verified = sha256(target) == artifact['sha256']
    stat = ipfs.post('files/stat', params={'arg': mfs_path}).json()
    if not verified or stat['Hash'] != artifact['cid']:
        raise RuntimeError('Dummy retrieval or Desktop Files reference verification failed.')
    report = {'kind': 'dummy_local_storage_demo', 'started_utc': started,
        'completed_utc': datetime.now(timezone.utc).isoformat(), 'file_bytes': source.stat().st_size,
        'cid': artifact['cid'], 'sha256': artifact['sha256'], 'mfs_path': mfs_path,
        'upload_seconds': upload_seconds, 'retrieval_seconds': retrieval_seconds,
        'hash_verified': verified, 'bandwidth_before': before,
        'bandwidth_after': ipfs.post('stats/bw').json(),
        'peers': ipfs.post('swarm/peers').json().get('Peers') or [],
        'note': 'HTTP RPC/file traffic on localhost; not peer-to-peer bandwidth or a model result.'}
    write_json(folder/'report.json', report)
    print('Retrieved by CID; SHA-256 matched. Dummy file is visible under Files > project-demos.', flush=True)
    print('The peer bandwidth graph can stay at zero: no other IPFS peers are connected.', flush=True)
    print(f'Report: {folder / "report.json"}', flush=True)
    record(f'IPFS dummy traffic demonstration completed: CID={artifact["cid"]}; bytes={source.stat().st_size}; hash verified; MFS={mfs_path}; report={folder / "report.json"}.')


if __name__ == '__main__':
    try:
        main()
    except Exception as exc:
        record(f'IPFS dummy demo error: {type(exc).__name__}: {exc}')
        raise
